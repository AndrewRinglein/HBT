#!/usr/bin/env node
// The base heroes' descriptions — what the first draft shows instead of numbers. kingdom.opening-draft-modifiers
// (2026-10-03). Ruled 2026-10-03 (Andrew, engine/DECISIONS.md 'the opening run, audited'): "the first hero is chosen
// from 3, but no stats or badges shown, just a description."
//
//   node tools/mk-descriptions.mjs [--codex ../content/hbt-content.json]
//
// The engine's unit rows carry no words about who a hero is; the codex does — each hero's `backstory` and `quote`
// (content/gen/heroes.json, ported from Hell-TCG). This writes them for the base heroes (hero.base.*, the draft pool),
// keyed by id, and nothing else: no stat, no badge, no kit. A base hero the codex gives no backstory is named in the
// header and left out — the draft then shows its name and class alone (kingdom SWITCHES.md openingFirstDraftDescription).
// Deterministic: same input, same bytes.
//
// Writes src/content/generated/descriptions.ts. Never hand-edit; regenerate.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'

const argv = process.argv.slice(2)
const val = (f, d) => { const i = argv.indexOf(f); return i >= 0 ? argv[i + 1] : d }
const CODEX = val('--codex', '../content/hbt-content.json')
const OUT = 'src/content/generated/descriptions.ts'
const codex = JSON.parse(readFileSync(CODEX, 'utf8'))
const fail = (msg) => { console.error(`mk-descriptions: ${msg}`); process.exit(1) }

const heroes = codex.heroes?.heroes
if (!Array.isArray(heroes)) fail(`${CODEX} has no heroes.heroes list`)
const base = heroes.filter((h) => typeof h.id === 'string' && h.id.startsWith('hero.base.')).sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
if (new Set(base.map((h) => h.id)).size !== base.length) fail('duplicate base hero id in the codex')
const words = (s) => (typeof s === 'string' ? s.trim() : '')
const rows = base.filter((h) => words(h.backstory)).map((h) => ({ id: h.id, description: words(h.backstory), quote: words(h.quote) }))
const none = base.filter((h) => !words(h.backstory)).map((h) => h.id)

mkdirSync('src/content/generated', { recursive: true })
writeFileSync(OUT, `// GENERATED by tools/mk-descriptions.mjs from ${CODEX} (heroes.heroes[].backstory, .quote). Never hand-edit; regenerate.
// ${rows.length} base heroes described${none.length ? ` · no backstory in the codex: ${none.join(', ')}` : ''}.

/** Per base hero: who it is, in the codex's words — its backstory, and its quote ('' when the codex has none). */
export const HERO_DESCRIPTIONS: readonly { readonly id: string; readonly description: string; readonly quote: string }[] = [
${rows.map((r) => '  ' + JSON.stringify(r) + ',').join('\n')}
]
`)
console.log(`${OUT} — ${rows.length} base heroes described${none.length ? `, ${none.length} with no backstory: ${none.join(', ')}` : ''}`)
