#!/usr/bin/env node
// The codex's words for progress that the engine does not carry — G12 of GEAR-IMPLEMENTATION.md
// (screens.after-battle), cut to the campaign's half by kingdom.reads-engine (2026-10-02).
//
//   node tools/mk-progress.mjs [--codex ../content/hbt-content.json]
//
// kingdom.reads-engine (engine DECISIONS.md "the duplication review, ruled", findings K1 K15 K17): the level tables
// and the specialties' numbers are the ENGINE's (LEVELS, SPECIALTIES, levelTableOf — a civilian levels on its type
// table), read through src/engine.ts by src/content/progress.ts. This tool used to copy the class tables and the
// specialties, dropped the civilian type tables, and the kingdom levelled civilians on the wrong table. It now writes
// only what the engine does not carry:
//   · each specialty's intent (the level-up card's line) and the codex stat words the engine has no stat for
//     (itemSlots), keyed by the word;
//   · the classes — id and name, from codex.classes (K17: classes.ts was a hand copy); the group is the kingdom's own
//     column (src/content/classes.ts).
// Deterministic: same input, same bytes.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { statOf } from '../../content/stat-words.mjs'

const argv = process.argv.slice(2)
const val = (f, d) => { const i = argv.indexOf(f); return i >= 0 ? argv[i + 1] : d }
const CODEX = val('--codex', '../content/hbt-content.json')
const OUT = 'src/content/generated/progress.ts'
const codex = JSON.parse(readFileSync(CODEX, 'utf8'))
const fail = (msg) => { console.error(`mk-progress: ${msg}`); process.exit(1) }
const byId = (a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0)
const sorted = (o) => Object.fromEntries(Object.keys(o ?? {}).sort().map((k) => [k, o[k]]))

const specs = (Array.isArray(codex.specialties) ? codex.specialties : Object.values(codex.specialties))
  .map((s) => ({ id: s.id, intent: s.intent ?? '', campaignMods: sorted(Object.fromEntries(Object.entries(s.statModifiers ?? {}).filter(([k]) => !statOf(k)))) }))
  .sort(byId)
const seen = new Set()
for (const s of specs) { if (seen.has(s.id)) fail(`duplicate specialty '${s.id}'`); seen.add(s.id) }

const classes = codex.classes.map((c) => {
  if (typeof c.id !== 'string' || !c.id.startsWith('class.') || typeof c.name !== 'string') fail(`a codex class row has no class.* id or no name: ${JSON.stringify(c).slice(0, 80)}`)
  return { id: c.id, name: c.name }
})
if (new Set(classes.map((c) => c.id)).size !== classes.length) fail('duplicate class id in codex.classes')

mkdirSync('src/content/generated', { recursive: true })
writeFileSync(OUT, `// GENERATED by tools/mk-progress.mjs from ${CODEX} (specialties, classes). Never hand-edit; regenerate.
// ${specs.length} specialties' campaign words · ${classes.length} classes.
//
// The level tables and the specialties' numbers are the engine's (src/content/progress.ts reads them through
// src/engine.ts). ${codex.levels.rules?.specialty ? 'Codex rule: ' + JSON.stringify(codex.levels.rules.specialty) : ''}

/** Per specialty: the level-up card's line, and the codex stat words the engine has no stat for (itemSlots). */
export const SPECIALTY_WORDS: readonly { readonly id: string; readonly intent: string; readonly campaignMods: Readonly<Record<string, number>> }[] = [
${specs.map((s) => '  ' + JSON.stringify(s) + ',').join('\n')}
]

/** The codex's classes, in its order — id and name. */
export const CLASS_NAMES: readonly { readonly id: string; readonly name: string }[] = [
${classes.map((c) => '  ' + JSON.stringify(c) + ',').join('\n')}
]
`)
console.log(`${OUT} — ${specs.length} specialties' words, ${classes.length} classes`)
