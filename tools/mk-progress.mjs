#!/usr/bin/env node
// The codex's words for progress that the engine does not carry — G12 of GEAR-IMPLEMENTATION.md
// (screens.after-battle), cut to the campaign's half by kingdom.reads-engine (2026-10-02).
//
//   node tools/mk-progress.mjs [--codex ../content/hbt-content.json] [--out src/content/generated/progress.ts]
//
// kingdom.reads-engine (engine DECISIONS.md "the duplication review, ruled", findings K1 K15 K17): the level tables
// and the specialties' numbers are the ENGINE's (LEVELS, SPECIALTIES, levelTableOf — a civilian levels on its type
// table), read through src/engine.ts by src/content/progress.ts. This tool used to copy the class tables and the
// specialties, dropped the civilian type tables, and the kingdom levelled civilians on the wrong table. It now writes
// only what the engine does not carry:
//   · each specialty's intent (the level-up card's line) and the codex stat words the engine has no stat for
//     (itemSlots), keyed by the word;
//   · the classes — id and name, from codex.classes (K17: classes.ts was a hand copy); the group is the kingdom's own
//     column (src/content/classes.ts);
//   · kingdom.opening-first-hero-class-line (2026-10-04, engine DECISIONS.md 2026-10-04 'the opening's tutorial: the first hero's class line, …': "a line that
//     describes the class" · the hero's changes "in plain words, like 'Born leader' and 'Tougher than most'" — "3
//     correct."): the content's player-facing words, its rows' `playerLine` — each class's one sentence (`line` on its
//     row here; '' for a class the content gives none), each badge's plain words (BADGE_LINES) and, per stat in the
//     codex's word, the plain words for a hero given more of it (STAT_LINES). No such sentence is typed in the kingdom.
// Deterministic: same input, same bytes.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { statOf } from '../../content/stat-words.mjs'

const argv = process.argv.slice(2)
const val = (f, d) => { const i = argv.indexOf(f); return i >= 0 ? argv[i + 1] : d }
const CODEX = val('--codex', '../content/hbt-content.json')
const OUT = val('--out', 'src/content/generated/progress.ts')
const codex = JSON.parse(readFileSync(CODEX, 'utf8'))
const fail = (msg) => { console.error(`mk-progress: ${msg}`); process.exit(1) }
const byId = (a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0)
const sorted = (o) => Object.fromEntries(Object.keys(o ?? {}).sort().map((k) => [k, o[k]]))

const specs = (Array.isArray(codex.specialties) ? codex.specialties : Object.values(codex.specialties))
  .map((s) => ({ id: s.id, intent: s.intent ?? '', campaignMods: sorted(Object.fromEntries(Object.entries(s.statModifiers ?? {}).filter(([k]) => !statOf(k)))) }))
  .sort(byId)
const seen = new Set()
for (const s of specs) { if (seen.has(s.id)) fail(`duplicate specialty '${s.id}'`); seen.add(s.id) }

const classes = codex.classes.map((c) => {
  if (typeof c.id !== 'string' || !c.id.startsWith('class.') || typeof c.name !== 'string') fail(`a codex class row has no class.* id or no name: ${JSON.stringify(c).slice(0, 80)}`)
  if (c.playerLine !== undefined && (typeof c.playerLine !== 'string' || !c.playerLine.trim())) fail(`class '${c.id}' has an empty playerLine`)
  return { id: c.id, name: c.name, line: c.playerLine ?? '' }
})
/* the plain words of the rows that carry them, by id, sorted */
const linesOf = (rows, what) => sorted(Object.fromEntries((rows ?? []).filter((r) => r && r.playerLine !== undefined).map((r) => {
  if (typeof r.id !== 'string' || typeof r.playerLine !== 'string' || !r.playerLine.trim()) fail(`a codex ${what} row has an empty playerLine: ${JSON.stringify(r).slice(0, 80)}`)
  return [r.id, r.playerLine]
})))
const badgeLines = linesOf(codex.badges, 'badge'), statLines = linesOf(codex.stats, 'stat')
// rule.special-moves-unlock-at-level-two (engine item, 2026-10-06; engine DECISIONS.md 'a hero's special moves unlock at level
// 2, ruled …': "the level-up screen should name the moves unlocked"): the Codex's one line for a class's bonus move — its
// class row's `bonusMoveNote` beside `bonusMove` — by class and move. Which move a hero has and at what level is the engine's
// row; only the words are carried here. A class with a bonus move and no note carries ''.
const moveLines = codex.classes.filter((c) => typeof c.bonusMove === 'string').map((c) => {
  if (c.bonusMoveNote !== undefined && typeof c.bonusMoveNote !== 'string') fail(`class '${c.id}' has a bonusMoveNote that is not words`)
  return { classId: c.id, moveId: c.bonusMove, line: (c.bonusMoveNote ?? '').trim() }
})
if (new Set(classes.map((c) => c.id)).size !== classes.length) fail('duplicate class id in codex.classes')

if (OUT === 'src/content/generated/progress.ts') mkdirSync('src/content/generated', { recursive: true })
writeFileSync(OUT, `// GENERATED by tools/mk-progress.mjs from ${val('--codex', null) ? 'the codex named' : CODEX} (specialties, classes, badges, stats). Never hand-edit; regenerate.
// ${specs.length} specialties' campaign words · ${classes.length} classes · ${Object.keys(badgeLines).length} badges' and ${Object.keys(statLines).length} stats' plain words.
//
// The level tables and the specialties' numbers are the engine's (src/content/progress.ts reads them through
// src/engine.ts). ${codex.levels.rules?.specialty ? 'Codex rule: ' + JSON.stringify(codex.levels.rules.specialty) : ''}

/** Per specialty: the level-up card's line, and the codex stat words the engine has no stat for (itemSlots). */
export const SPECIALTY_WORDS: readonly { readonly id: string; readonly intent: string; readonly campaignMods: Readonly<Record<string, number>> }[] = [
${specs.map((s) => '  ' + JSON.stringify(s) + ',').join('\n')}
]

/** The codex's classes, in its order — id, name, and its one player-facing sentence (line; empty where the content gives none). */
export const CLASS_NAMES: readonly { readonly id: string; readonly name: string; readonly line: string }[] = [
${classes.map((c) => '  ' + JSON.stringify(c) + ',').join('\n')}
]

/** Per badge that carries them: what it makes the hero, in the content's plain words. */
export const BADGE_LINES: Readonly<Record<string, string>> = {
${Object.entries(badgeLines).map(([k, v]) => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(v) + ',').join('\n')}
}

/** Per stat (the codex's word) that carries them: the content's plain words for a hero given more of it. */
export const STAT_LINES: Readonly<Record<string, string>> = {
${Object.entries(statLines).map(([k, v]) => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(v) + ',').join('\n')}
}

/** Per class that has one: its bonus move and the Codex's one line of what the move does (the class row's bonusMoveNote). */
export const MOVE_LINES: readonly { readonly classId: string; readonly moveId: string; readonly line: string }[] = [
${moveLines.map((m) => '  ' + JSON.stringify(m) + ',').join('\n')}
]
`)
console.log(`${OUT} — ${specs.length} specialties' words, ${classes.length} classes (${classes.filter((c) => c.line).length} with a player-facing line), ${Object.keys(badgeLines).length} badges' and ${Object.keys(statLines).length} stats' plain words`)
