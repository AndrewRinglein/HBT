#!/usr/bin/env node
// The kingdom's level tables and specialties, generated from the codex — G12 of
// GEAR-IMPLEMENTATION.md (screens.after-battle).
//
//   node tools/mk-progress.mjs [--codex ../content/hbt-content.json]
//
// Reads content/hbt-content.json (levels.classes, specialties) and writes
// src/content/generated/progress.ts. The kingdom never types a level row or a
// specialty by hand (CLAUDE.md: "Never hand-edit generated/"). What a level DOES
// to a fielded unit is the engine's (applyProgress at fielding, hero assembly
// 2026-09-03); the kingdom records the level, the specialty and the level-5 pick
// on the hero, shows the grants on the level-up screen, and hands the engine
// `heroProgress` through the seam. Deterministic: same input, same bytes.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'

const argv = process.argv.slice(2)
const val = (f, d) => { const i = argv.indexOf(f); return i >= 0 ? argv[i + 1] : d }
const CODEX = val('--codex', '../content/hbt-content.json')
const OUT = 'src/content/generated/progress.ts'
const codex = JSON.parse(readFileSync(CODEX, 'utf8'))
const fail = (msg) => { console.error(`mk-progress: ${msg}`); process.exit(1) }
const sorted = (o) => Object.fromEntries(Object.keys(o ?? {}).sort().map((k) => [k, o[k]]))

const tables = []
for (const c of codex.levels.classes) {
  if (!Array.isArray(c.rows) || !c.rows.length) fail(`${c.id} has no level rows`)
  const rows = c.rows.map((r) => {
    if (!Number.isInteger(r.level)) fail(`${c.id}: a row has no integer level`)
    const row = { level: r.level, grants: sorted(r.grants), specialty: !!r.specialty }
    if (r.choice) {
      if (r.choice.pick !== 1 || !Array.isArray(r.choice.options)) fail(`${c.id} level ${r.level}: a choice must pick 1 from options[]`)
      row.choice = r.choice.options.map(sorted)
    }
    return row
  }).sort((a, b) => a.level - b.level)
  tables.push({ id: c.id, name: c.name, freebie: sorted(c.freebie), rows })
}
tables.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))

const specs = (Array.isArray(codex.specialties) ? codex.specialties : Object.values(codex.specialties))
  .map((s) => ({ id: s.id, name: s.name, classId: s.class, intent: s.intent ?? '', statModifiers: sorted(s.statModifiers), powers: [...(s.powers ?? [])] }))
  .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
const seen = new Set()
for (const s of specs) { if (seen.has(s.id)) fail(`duplicate specialty '${s.id}'`); seen.add(s.id); if (!tables.some((t) => t.id === s.classId)) fail(`${s.id} is for ${s.classId}, which has no level table`) }

mkdirSync('src/content/generated', { recursive: true })
writeFileSync(OUT, `// GENERATED by tools/mk-progress.mjs from ${CODEX} (levels.classes, specialties). Never hand-edit; regenerate.
// ${tables.length} level tables · ${specs.length} specialties.
//
// The shape is src/content/progress.ts's. ${codex.levels.rules?.specialty ? 'Codex rule: ' + JSON.stringify(codex.levels.rules.specialty) : ''}

import type { LevelTable, SpecialtyRow } from '../progress.js'

export const LEVEL_TABLES: readonly LevelTable[] = [
${tables.map((t) => '  ' + JSON.stringify(t) + ',').join('\n')}
]

export const SPECIALTY_ROWS: readonly SpecialtyRow[] = [
${specs.map((s) => '  ' + JSON.stringify(s) + ',').join('\n')}
]
`)
console.log(`${OUT} — ${tables.length} level tables, ${specs.length} specialties`)
