#!/usr/bin/env node
// viewer.characters-stand-out (engine DECISIONS.md 2026-10-03 'the characters must stand out from the board'). Andrew: "the
// characters don't stand out enough against the backdrop. They look a little too small on the screen. … And what else can we
// do to make the characters stand out more? … Do we need more shadows? I don't know what we need." · "Actually, let's change
// this to 30% bigger characters, 10% smaller hexes." Builds CHARACTERS-STAND-OUT.html — the review page: the Orphanage on the
// battle screen as it is today, with each look to judge alone, and with all of them together, one link each
// (BATTLE-SANDBOX.html?play=<the Orphanage>&look=<names>). Nothing here is typed by hand: the looks and the words that say
// what each does are the viewer's (viewer src/stand-out.js LOOKS), the battle is the sandbox's own Orphanage. What Andrew
// accepts becomes the default in a later item. Open it from the game's server: http://127.0.0.1:4230/kingdom/CHARACTERS-STAND-OUT.html
//
//   node tools/build-stand-out.mjs [out]      (default CHARACTERS-STAND-OUT.html) — generated, never hand-edit
import '../../engine/tools/engine-modules.mjs'   // first: links engine/node_modules into a worker's copy (Andrew, 2026-10-01)
import {writeFileSync} from 'node:fs'
import {createRequire} from 'node:module'
import {LOOKS} from '../../viewer/src/stand-out.js'
const esbuild=createRequire(import.meta.url)('../../engine/node_modules/esbuild')
const built=esbuild.buildSync({stdin:{contents:`export {SANDBOX_ENCOUNTERS} from './src/content/sandbox.ts'`,resolveDir:process.cwd(),loader:'ts'},bundle:true,platform:'node',format:'esm',write:false,logLevel:'silent'})
const {SANDBOX_ENCOUNTERS}=await import('data:text/javascript;base64,'+Buffer.from(built.outputFiles[0].text).toString('base64'))
const BATTLE='encounter.opening.orphanage'
const battle=SANDBOX_ENCOUNTERS.find(e=>e.id===BATTLE);if(!battle)throw Error(`stand-out review: the sandbox does not play ${BATTLE}`)
const esc=s=>String(s).replace(/[&<>"]/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'})[c])
const names=Object.keys(LOOKS)
const rows=[{look:[],title:'As it is today',words:'No look named: the battle screen unchanged, to compare against.'},
 ...names.map(n=>({look:[n],title:LOOKS[n],words:'This look alone.'})),
 {look:names,title:'All of them together',words:names.map(n=>LOOKS[n]).join(' · ')}]
const href=look=>`BATTLE-SANDBOX.html?play=${BATTLE}${look.length?'&look='+look.join(','):''}`
const card=r=>`<a class="card" href="${esc(href(r.look))}" data-look="${esc(r.look.join(','))}"><b>${esc(r.title)}</b><span>${esc(r.words)}</span><i>Open the ${esc(battle.name)} ▸</i></a>`
const html=`<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Heroes of Blight and Tragic — the characters stand out</title><!-- Generated by kingdom/tools/build-stand-out.mjs — never hand-edit -->
<style>
:root{--bg:#0b0c0e;--panel:#15140f;--line:#3a3020;--gold:#d8b46a;--ink:#e9e1c9;--dim:#9a917a}
*{box-sizing:border-box}html,body{margin:0;background:var(--bg);color:var(--ink);font-family:'Barlow Semi Condensed',system-ui,sans-serif}
main{max-width:980px;margin:0 auto;padding:48px 28px 64px}
.house{letter-spacing:.32em;text-transform:uppercase;color:var(--gold);font-size:13px;font-weight:600}
h1{font-family:Spectral,Georgia,serif;font-weight:600;font-size:40px;margin:8px 0 6px}header p{color:var(--dim);font-size:17px;margin:0 0 30px;line-height:1.45}
.list{display:grid;gap:14px}
.card{display:grid;grid-template-columns:1fr auto;gap:4px 20px;align-items:center;text-decoration:none;color:inherit;background:var(--panel);border:1px solid var(--line);border-radius:6px;padding:18px 22px;transition:border-color .15s}
.card:hover,.card:focus-visible{border-color:var(--gold);outline:none}
.card b{font-family:Spectral,Georgia,serif;font-size:23px;font-weight:600}.card span{grid-column:1;color:var(--dim);font-size:16px}
.card i{grid-column:2;grid-row:1 / span 2;font-style:normal;color:var(--gold);font-weight:700;font-size:17px;white-space:nowrap}
</style></head><body><main>
<header><div class="house">Heroes of Blight and Tragic</div><h1>The characters stand out — looks to judge</h1>
<p>The ${esc(battle.name)} on the battle screen: as it is today, with each look alone, and with all of them together. Each opens the same battle; nothing here is a default yet — what you accept becomes one.</p></header>
<section class="list">
${rows.map(card).join('\n')}
</section></main></body></html>
`
const out=process.argv[2]??'CHARACTERS-STAND-OUT.html';writeFileSync(out,html)
console.log(`${out}: ${Buffer.byteLength(html)} bytes; ${rows.length} links to ${battle.name} (${rows.map(r=>r.look.join('+')||'as today').join(', ')})`)
