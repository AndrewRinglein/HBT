#!/usr/bin/env node
// The Codex's words about an item and what it grants — what an item card shows. kingdom.equip-item-card (2026-10-05).
// Ruled 2026-10-05 (Andrew, engine/DECISIONS.md 'playtest post: notices, target lines, item cards, …'): "When you're selecting
// items in the equipment phase, you need to be able to look at your items somehow. You need to be able to click on them, and
// then they pop up somewhere on the screen, to the right or somewhere, as a card with a description."
//
//   node tools/mk-item-words.mjs [--codex ../content/hbt-content.json] [--out src/content/generated/item-words.ts]
//
// The engine's rows carry an item's battle facts and no words about it; the Codex does. This writes, and nothing else:
//   · per Codex item, its one line of what it is (`intent`) and its own triggers as the Codex words them (hook, effect, chance);
//   · per Codex Enchantment or attribute, its name, its line and its triggers — a Forge row carries one;
//   · per attack or power that some item or attribute GRANTS, the Codex's own fields about it: an attack's targets, stat,
//     damage, type, hits, Stamina, Accuracy, Crit, triggers and line; a power's Stamina, cooldown, targets, description and
//     line. src/content/item-card.ts words them; no sentence is composed here.
// A granted id that is neither an attack nor a power (a badge, a tag) is not a row here. Deterministic: same input, same bytes.
//
// Writes src/content/generated/item-words.ts. Never hand-edit; regenerate.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname } from 'node:path'

const argv = process.argv.slice(2)
const val = (f, d) => { const i = argv.indexOf(f); return i >= 0 ? argv[i + 1] : d }
const CODEX = val('--codex', '../content/hbt-content.json')
const OUT = val('--out', 'src/content/generated/item-words.ts')
const codex = JSON.parse(readFileSync(CODEX, 'utf8'))
const fail = (msg) => { console.error(`mk-item-words: ${msg}`); process.exit(1) }
for (const k of ['items', 'enchants', 'attacks', 'powers']) if (!Array.isArray(codex[k])) fail(`${CODEX} has no ${k} list`)

const words = (s) => (typeof s === 'string' ? s.trim() : '')
const byIdOrder = (a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0)
const unique = (rows, what) => { const seen = new Set(); for (const r of rows) { if (seen.has(r.id)) fail(`duplicate ${what} id '${r.id}'`); seen.add(r.id) } return rows }
/** A trigger as the Codex words it: the hook, the effect's sentence, and the chance when it is not certain. */
const triggersOf = (row) => (row.triggers ?? []).map((t) => {
  if (typeof t.hook !== 'string' || typeof t.effect !== 'string') fail(`${row.id}: a trigger without a hook and an effect in words: ${JSON.stringify(t)}`)
  return { hook: t.hook, effect: words(t.effect), ...(Number.isInteger(t.chance) && t.chance !== 100 ? { chance: t.chance } : {}) }
})

const items = unique(codex.items.map((i) => ({ id: i.id, line: words(i.intent), triggers: triggersOf(i) })).sort(byIdOrder), 'item')
const attributes = unique(codex.enchants.map((e) => ({ id: e.id, name: words(e.name), line: words(e.intent), triggers: triggersOf(e) })).sort(byIdOrder), 'enchant')
const granted = new Set([...codex.items, ...codex.enchants].flatMap((r) => r.grants ?? []))
const attacks = codex.attacks.filter((a) => granted.has(a.id)).map((a) => ({
  id: a.id, name: words(a.name), kind: 'attack', targets: words(a.targets), stat: a.stat ?? null, damage: a.damage ?? 0, damageType: a.damageType ?? null,
  hits: a.hits ?? 1, stamina: a.stamina ?? 0, accuracy: a.accuracy ?? 0, crit: a.crit ?? 0, triggers: triggersOf(a), line: words(a.intent),
}))
const powers = codex.powers.filter((p) => granted.has(p.id)).map((p) => ({
  id: p.id, name: words(p.name), kind: 'power', targets: words(p.targets), stamina: p.stamina ?? 0, cooldown: p.cooldown ?? 0, free: p.free === true,
  description: words(p.description), triggers: triggersOf(p), line: words(p.intent),
}))
const grants = unique([...attacks, ...powers].sort(byIdOrder), 'granted action')
const noLine = items.filter((i) => !i.line).map((i) => i.id)

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, `// GENERATED by tools/mk-item-words.mjs from ${CODEX} (items[], enchants[], attacks[], powers[]). Never hand-edit; regenerate.
// ${items.length} items' lines · ${attributes.length} Enchantments and attributes · ${grants.length} granted attacks and powers (${attacks.length} attacks, ${powers.length} powers)${noLine.length ? ` · no line in the Codex: ${noLine.join(', ')}` : ''}.
//
// The Codex's own words and fields; src/content/item-card.ts makes the card from them and the engine's rows.

/** A trigger as the Codex words it: the hook, the effect's sentence, and the chance (percent) when it is not certain. */
export type TriggerWords = { readonly hook: string; readonly effect: string; readonly chance?: number }
/** Per Codex item: its one line of what it is, and its own triggers. */
export type ItemWords = { readonly id: string; readonly line: string; readonly triggers: readonly TriggerWords[] }
/** Per Codex Enchantment or attribute: its name, its line and its triggers. */
export type AttributeWords = { readonly id: string; readonly name: string; readonly line: string; readonly triggers: readonly TriggerWords[] }
/** An attack an item grants, in the Codex's own fields. */
export type AttackWords = { readonly id: string; readonly name: string; readonly kind: 'attack'; readonly targets: string; readonly stat: string | null; readonly damage: number; readonly damageType: string | null; readonly hits: number; readonly stamina: number; readonly accuracy: number; readonly crit: number; readonly triggers: readonly TriggerWords[]; readonly line: string }
/** A power an item grants, in the Codex's own fields. */
export type PowerWords = { readonly id: string; readonly name: string; readonly kind: 'power'; readonly targets: string; readonly stamina: number; readonly cooldown: number; readonly free: boolean; readonly description: string; readonly triggers: readonly TriggerWords[]; readonly line: string }

export const ITEM_WORDS: readonly ItemWords[] = [
${items.map((r) => '  ' + JSON.stringify(r) + ',').join('\n')}
]

export const ATTRIBUTE_WORDS: readonly AttributeWords[] = [
${attributes.map((r) => '  ' + JSON.stringify(r) + ',').join('\n')}
]

export const GRANT_WORDS: readonly (AttackWords | PowerWords)[] = [
${grants.map((r) => '  ' + JSON.stringify(r) + ',').join('\n')}
]
`)
console.log(`${OUT} — ${items.length} items, ${attributes.length} attributes, ${grants.length} granted actions (${attacks.length} attacks, ${powers.length} powers)${noLine.length ? `; ${noLine.length} items with no line` : ''}`)
